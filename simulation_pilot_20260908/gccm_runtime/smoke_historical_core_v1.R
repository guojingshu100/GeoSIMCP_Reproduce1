args <- commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==4)
source(args[1], local=.GlobalEnv)
library(foreach)
library(doParallel)
needed <- c("generateEmbedings","laggedVar4Lattic","GCCMLattice","GCCMSingle4Lattice","simplex_projection","compute_stats")
stopifnot(all(vapply(needed, exists, logical(1), mode="function")))
dat <- read.csv(args[2], check.names=FALSE)
edges <- read.csv(args[3])
n <- nrow(dat)
stopifnot(identical(dat$node_id, seq_len(n)), !anyDuplicated(dat$sample_id))
nb <- lapply(seq_len(n), function(i) sort(unique(c(edges$v[edges$u==i],edges$u[edges$v==i]))))
stopifnot(all(lengths(nb)>0))
emb <- generateEmbedings(nb, dat$abs_residual, 3)
stopifnot(identical(dim(emb),c(n,3L)), all(is.finite(emb)))
for(k in 1:3) stopifnot(all(lengths(laggedVar4Lattic(nb,k))>0))
idx <- rep(TRUE,n)
fit <- simplex_projection(emb, dat$z_x1, idx, idx, 4)
stopifnot(all(is.finite(fit$pred)),fit$stats$N==n)
set.seed(42)
raw <- GCCMLattice(emb, dat$z_x1, c(10,30,n-2), c(1,n),c(1,n),3,tau=1,b=4,cores=NULL)
stopifnot(nrow(raw)==2*(n-2)+1,all(is.finite(raw$rho)))
write.csv(raw,file.path(args[4],"smoke_raw.csv"),row.names=FALSE)
write.csv(emb,file.path(args[4],"smoke_embedding.csv"),row.names=FALSE)
cat("DIRECTION=effect_xmap_cause\nVALID_EMBEDDINGS=",n,"\nFUNCTIONS=",paste(needed,collapse=","),"\n")
print(sessionInfo())
